"""
`model_role=eval.qa_generation` 的提示词：第一层检索评测的出题。

谁用它
------
`RetrievalEvalServiceImpl` 里那条后台任务（handler
`retrieval_eval.generate`）。它把抽中的 chunk 分批丢进来，每一批要
「问题 + 逐字答案」。

⚠️ 这里的每一句禁止条款都是**评测有效性**的前提，不是风格建议
----------------------------------------------------------------
这是本提示词与仓库里其它提示词最大的不同：别的提示词产出的是"给人看
或给人改"的东西（画像、摘要、结构化记忆），而这份产出的是**ground
truth**。一道「公司为什么在 2024 年收缩业务？」的题，若原文只写了「营收
下降 12%」和「关闭两条产线」，它是**格式完全合法、答案也确实是原文片段**
的 —— 而它正确的回答需要推断，原文从没说过因果。

后果是：检索把正确的 chunk 排在第一位，模型照样答不出来，而那会被记成
「没召回到」。**一个凭空出现的召回失败**，且没有任何东西指向这道题本身。

服务端校验（`eval/output.py` 的 parse + `eval/generator.py` 的
validate_items）只能拦住机械可判的那部分（id 认不认识、答案是不是逐字
子串、问题重不重复）。跨 chunk 推断、外部知识、计算、逻辑跳跃**机器判
不了** —— 只能靠这份文本事先堵住。这是这一层已知的、写在明面上的局限。

⚠️ 输出形状是**手写**在 TEXT 里的，不是从 pydantic 模型导出的
--------------------------------------------------------
与 memory 那几份提示词同一做法：提示词模块不 import 服务层（agent 不该
依赖 services）。代价是文本里那份 JSON 形状可能与服务端的 pydantic 模型
漂移 —— 所以有一条测试拿服务端的 `WindowQuestions.model_fields` 去比对
这里的字段名（`tests/services/document/test_eval_prompt_contract.py`）。
改任何一边都会让那条测试红。不要删它。
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any, Protocol

from app.agent.model import ModelRole

from ..contracts import PromptDefinition

__all__ = ["PROMPT", "TEXT", "ChunkLike", "render_user_message"]


class ChunkLike(Protocol):
    """本提示词只需要这两样。"""

    def __getitem__(self, key: str) -> Any: ...


TEXT = """\
你在为一份文档档案构建**检索**测试集。给定若干段正文（下称 chunk），
为**每一段**分别产出若干「问题 + 答案原文」。

这些问题的用途是**拿去检索**：系统会把它当成用户的查询词，去索引里
找答案所在的那段正文。所以：

    ✅ 问题要像真人会输入的那样（带主体名、带时间锚点）
    ❌ 问题不要像阅读理解题的题干

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
最重要的约束：这是**检索**基准，不是**推理**基准
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

**问题的答案必须在那一段 chunk 里被明确写出来。** 一字不差地写着。

不符合这一条的问题会让这个测试集失去意义 —— 因为检索系统即使把
正确的 chunk 排在了第一位，模型也答不出来，而那会被记成「没召回到」。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
主体从哪来（**先读这一节，它决定问题能不能用**）
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

每一段正文上面都标着它所属的文档：

    所属文档：特锐德（300001.SZ）

**问题里的主体必须用这个**，不要用正文里的说法。因为正文常常写的是
「本公司」「本报告期」这类**没有主体**的指代 —— 它是一个名词，但它在
索引里**不指向任何一家公司**：一百家公司的同类事件全都长成那样。照抄它
的后果有两个，都很严重：

    1. **问题无法检索**：查询词与其他几十家公司的同类事件完全一样，
       检索只能返回一堆混杂的结果 —— 命中与否取决于运气
    2. **产出成百条逐字重复的题**：每家公司各出一条，文本一模一样，
       彼此毫无区分度，对评测没有任何额外信息

⚠️ 主体**只写一个**：名称与代码不要同时出现
-----------------------------------------
「所属文档」那一行同时给了名称与代码，但**写进问题时只能挑一个**：

    ✅ 优先用**名称**（人问问题时就是说名字）
    ✅ 名称缺失时才用**代码**
    ❌ 两个都写 ——「特锐德（300001.SZ）截至…」

为什么不许两个都写：

    · **加权被稀释**：查询里多出来的那串代码在语料里几乎不重复出现，
      它拿走的是一份**不该给**的权重；而真正判别的那几个词（时间、
      事项）占的比例被压低，排序反而变差。
    · **不像真人提问**：没人会对着检索框同时敲公司名和证券代码。

所以：

    ✅ 「特锐德 截至 2007-12-31 经审计的净资产是多少？」
    ✅ 「300001.SZ 截至 2007-12-31 经审计的净资产是多少？」（名称缺失时）
    ❌ 「特锐德（300001.SZ）截至 2007-12-31 经审计的净资产是多少？」
    ❌ 「截至 2007-12-31 本公司经审计的净资产是多少？」
    ❌ 「该主体报告期内的净资产是多少？」

同时把**时间锚点**也写进去（哪一年、哪个报告期、哪一天）—— 同一家公司
会有几十条同类事件，没有时间的问题会同时命中它们。

⚠️ 主体来自**文档**，但**答案仍然只能来自正文**
------------------------------------------------
两件事，别混：

    主体（写进问题）   取「所属文档」的标题与业务标识
    答案（写进答案）   **必须逐字出自该 chunk 的正文**

不能反过来用文档里的信息当答案（比如拿证券代码去答一个问代码的题，而
正文里根本没写它）。正文里没有的，就是没有。

具体来说，**允许**的问题（括号里是为什么它安全）：

1. 明确写出的实体/属性。
   原文「公司成立于 1998 年」→ 问「成立于哪一年」。
2. 明确写出的数值/单位。
   原文「2024 年营收 124 亿元」→ 问「2024 年报告的营收是多少」。
3. 明确列出的项。
   原文列出产品 A、B、C → 问「列出了哪些产品」。**不得**推断未列出的项。
4. 明确写出的时间/地点/人物/机构。
   只问那些**字面出现**的。原文没写地点就不问地点。
5. 明确写出的定义/归类。
   原文「X 被归类为 Y」→ 问「chunk 把 X 归为哪一类」。
6. 明确写出的比较。
   **两个值与被比较关系都写出来**时才可以问。原文没说出的差值、比例
   一律不能问 —— 那是计算，不是检索。
7. 明确写出的因果。
   原文「报告将下滑归因于需求疲软」→ 问「报告给出的原因是什么」。
   ⚠️ 两个事实**相邻出现**不等于有因果关系。原文并排写了「营收下降」
   和「关闭产线」，**不能**问「为什么关闭产线」。
8. 明确写出的否定/限制/状态。
   原文「试验未纳入 12 岁以下儿童」→ 问「排除了哪个年龄段」。
   否定与范围要原样保留。
9. 明确写出的步骤/顺序。
   只在原文真的描述了步骤或顺序时问。不得补全缺失的步骤。
10. 表格/结构化内容。
    只有当该值所在的行/列表头或上下文**也在这一 chunk 内**时才问，
    否则那个值是有歧义的。

**禁止**的问题：

- ❌ **跨 chunk**：答案需要看另一段才完整的问题。每道题只能依赖它自
  己那一段。
- ❌ **推断因果**：把并列、先后、同时出现写成「为什么/怎么会」。
- ❌ **逻辑跳跃**：问某个事实「意味着什么」「证明了什么」「会导致
  什么」「暗示了什么」—— 除非这层含义是原文**明说**的。
- ❌ **预测/建议/评价**：问接下来会怎样、该怎么做、好不好、该采取
  什么策略。
- ❌ **外部知识**：补全常识、通用定义、缩写含义、缺失的单位、背景
  信息。原文没有的就是没有。
- ❌ **合成答案**：把两条不相关的陈述合成一个新结论。
- ❌ **计算**：算总和、百分比、差值、排名、单位换算 —— 除非结果本身
  在原文里写着。
- ❌ **无主体指代**：「本公司」「本报告期」「该主体」「它」「他们」
  「该公司」—— **一律不许出现在问题里**。主体必须写成「所属文档」给出的
  **名称或代码（只写一个）**（见上面「主体从哪来」那一节）。
  ⚠️ 正文里这么写是常态，但问题不能跟着写：那样的问题在索引里与其它
  几十家公司的同类事件完全无法区分。
- ❌ **主体写两遍**：「特锐德（300001.SZ）」「特锐德 300001.SZ」——
  名称与代码只挑一个，理由见上面「主体只写一个」那一段。
- ❌ **预设未写出的前提**：原文没说 X 停止，就不能问「X 什么时候
  停止的」。
- ❌ **超出 chunk 边界**：绝不用另一个 chunk、文档背景或模型记忆来
  补答案。
- ❌ **同义改写充数**：同一段里把同一个事实换种说法再问一遍，
  不算一道新题。每道题要测**不同**的明确事实。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
答案必须是**逐字复制**的原文片段
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

`answer_original` 是从该 chunk 正文里**原样复制**的一段连续文字：

    ✅ 原文「2023 年公司 A 报告营收 80 亿元」
       答案写「80 亿元」
    ❌ 答案写「80 亿」

    ✅ 原文「报告将 12% 的同比下滑归因于内需疲软」
       答案写「内需疲软」
    ❌ 答案写「因为内需疲软」（多了原文没有的「因为」）

服务端会拿 `answer_original` 去正文里做**精确匹配**来定位答案位置。
匹配不上的会被丢弃 —— 那道题就白出了。所以：不要改写、不要拼接、
不要增删标点或空格。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
题数
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

每段 chunk 尽量产出要求条数的**互不相同**的题。
若某段实在凑不出那么多（内容太短、或就那么一个明确事实），就**少出**
并把它的 id 填进 `insufficient_fact_chunk_ids`。

⚠️ **不要为了凑数而出模糊的、推断的、或重复的题。** 一道坏题对数据
集的损害大于一道少题 —— 坏题会让召回率看起来偏低且无法归因。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
输出格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

**只输出一个 JSON 对象**，不要任何解释文字，不要 markdown 代码块
（不要用 ``` 包裹）。形状严格如下：

{
  "items": [
    {
      "chunk_id": "输入里给出的那串 id，逐字复制",
      "question": "一个能用该 chunk 内原文直接回答的问题",
      "answer_original": "从该 chunk 正文里逐字复制的连续片段"
    }
  ],
  "insufficient_fact_chunk_ids": ["凑不够题数的那些 chunk 的 id"]
}

两个字段都必填（没有凑不够的 chunk 时 `insufficient_fact_chunk_ids`
给空数组）。一道题都出不了时 `items` 给空数组 —— 那是合法结果，
硬凑出来的题是噪音。
"""


def render_user_message(
        chunks: Sequence[Any],
        questions_per_chunk: int,
) -> str:
    """
    可变部分：这一次要出题的是哪些 chunk。

    `chunks` 的元素至少要有 `chunk_id` 与 `content`（可以是 dict，也可以
    是带这两个键的对象）。

    ⚠️ id 必须**明写**出来，不能让模型自己推
    ------------------------------------
    模型要把 chunk_id 原样回填，而它没法凭正文反推出一个 UUID。不给它
    明确的串，它会编一个看起来像 UUID 的东西 —— 那种错误服务端拦得住
    （认不出的 id），但代价是**整个窗口白跑**（几百次调用里的一次浪费，
    而且要等重试才知道）。

    每段正文用 `\"\"\"` 围起来：正文里可能有 markdown 标题、表格、或者
    本身就是一段话，围起来才分得清"哪段到哪段结束"。
    """

    lines: list[str] = []

    for index, chunk in enumerate(chunks):

        chunk_id = chunk["chunk_id"]
        content = str(chunk.get("content") or "")

        lines.append(f"### 片段 {index + 1}")
        lines.append(f"chunk_id: {chunk_id}")

        # 主体：**贴着正文给**，不是放系统提示词的全局背景。
        #
        # 一个窗口里的 chunk 可能来自不同文档（抽样是跨文档的），所以
        # "这份档案是谁的"必须逐块给 —— 全局给一次的话，来自 A 公司的
        # chunk 会被写成 B 公司的题，而且不报错。
        lines.append(f"所属文档：{_subject_of(chunk)}")

        lines.append("正文：")
        lines.append('"""')
        lines.append(content)
        lines.append('"""')
        lines.append("")

    # ⚠️ 具体数字放在**贴着数据**的这一段，而不是只在系统提示词里说一次。
    # 模型对"刚出现的具体数字"的遵守度明显更高 —— 系统提示词里那句话离
    # 数据隔了整整一屏。
    lines.append(
        f"请为上面每一段 chunk 分别产出最多 {questions_per_chunk} 道题。"
    )
    lines.append(
        "每道题必须写明它所依据的 chunk_id，答案必须是该段正文里逐字"
        "复制的片段。"
    )
    lines.append(
        "某段凑不出这么多道题时，少出并把它的 chunk_id 填进 "
        "insufficient_fact_chunk_ids。"
    )

    return "\n".join(lines)


def _subject_of(chunk: Any) -> str:
    """
    这段 chunk 的主体怎么写进提示词。

    形如 `特锐德（300001.SZ）`。两个都可能缺（`Document.title` 与
    `document_key` 本身都是可空的），缺了就说「未知」而**不编** ——
    编一个主体比留空更糟：模型会拿它去出题，而那道题指向一家不存在的
    公司，事后从数据集里完全看不出来。
    """

    title = (chunk.get("document_title") or "").strip()
    key = (chunk.get("document_key") or "").strip()

    if title and key:
        return f"{title}（{key}）"

    if title:
        return title

    if key:
        return key

    return "未知（文档未提供标题与业务标识 —— 不要凭空编主体）"


def _render(**_: Any) -> str:
    """系统提示词一个字都不随运行时数据变 —— 可变部分全在用户消息里。"""

    return TEXT


PROMPT = PromptDefinition(
    key=ModelRole.EVAL_QA_GENERATION,
    description=(
        "第一层检索评测的出题：从 chunk 正文产出「问题 + 逐字答案」，"
        "只允许原文明确写出的事实。"
    ),
    render=_render,
)
