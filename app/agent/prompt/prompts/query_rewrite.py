"""
查询改写提示词：把用户那句话改写成更适合检索的形式。

它要解决的是一件很具体的事
--------------------------
这批语料的问句里常带**文档级**信息（公司名、精确日期），而这些信息在
正文里往往不存在 —— 例如「荣安地产2007年4月12日披露的对外担保事项…」，
而那年正文写的是「公司披露「对外担保」事项」＋「成功信息产业(集团)
股份有限公司对…担保」（公司当年还叫那个名字）。公司名于是成了**指向
错块的锚**：它给同公司其它年份的块加分，把真正该命中的块压下去。

所以提示词里两条最要紧的规则是：

    日期 → 展开成两种写法（中文与短横线），因为正文散文写中文、
           `#### 2007-04-12 ｜ 对外担保` 这类小标题写短横线
    加别名/拆词 → 可以；**改语义/编事实 → 不可以**

最后一条是底线：改写只准让 query 更容易被找到，不准替用户改问题。
改不动就原样返回（`changed=false`）—— 硬改会让"这条 case 为什么没
命中"再也归因不到检索上。

契约是**批量**的（单条 = 长度为 1 的批）
-------------------------------------
输入是若干条待改写的查询（带编号），输出是**同样条数、同样编号**的
JSON。为什么不做成"一次一条"：

    一次评测的第 2 轮有几十条 case，逐条调模型就是几十次调用；
    而每次调用的固定开销（这 500 多 token 的系统提示词）都要重付一遍。

⚠️ 批量的最大风险不是失败，是**串号**：把甲的改写安到乙头上时，每一条
都读起来合理，只有对照原文才发现。所以提示词里把"条数与编号必须一致、
按输入顺序回"写成硬要求，而调用方（`retrieve/rewrite.py`）会逐条校验
编号 —— 对不上就整批不用、回落到逐条。提示词与校验必须成对存在：
少任何一边，串号就会静默发生。

输出契约写在这里（不设 response_format）
------------------------------------
与出题那份同理（见 eval/generator.py 的说明）：**不设** `response_format`，
JSON 形状写在提示词里，回包由调用方用 pydantic 校验。解析失败按"改写
失败"处理：退回原文并标 degraded，**不影响检索**。
"""

from __future__ import annotations

from typing import Any

from app.agent.model import ModelRole
from app.agent.prompt.contracts import PromptDefinition

__all__ = [
    "PROMPT",
    "render_user_message",
]

TEXT = """\
你在为一个中文检索系统做**查询改写**。输入是**若干条**用户问的话（带编号），\
你的输出是**同样条数、同样编号**的改写结果。

检索对象是上市公司的公告语料。它的正文有两个特点：
1. 正文里常常**不写公司名**，只写「公司」「本公司」—— 主体要从文档标题\
才看得出来；而用户提问时会带上公司名。
2. 正文里的日期有两种写法：散文里写「2007年4月12日」，而小节标题写\
「#### 2007-04-12 ｜ 对外担保」。关键词检索把它们当**不同的词**。

因此请遵守以下规则：

一、日期一律**两种写法都写上**（这是最重要的一条）
    - 「2007年4月12日」要补上「2007-04-12」
    - 「2007-04-12」要补上「2007年4月12日」
    - 短横线形式**月日补零**（2007年4月2日 -> 2007-04-02），
      因为检索侧只认补零的两位形式
    - 中文形式**不要**补零（正文就写作「2007年4月2日」）

二、可以在**不改变意图**的前提下：
    - 补上同义说法、简称与全称（如「ST海王」与「海王生物」）
    - 把口语化的说法换成公告里更可能出现的书面说法
    - 去掉「请问」「帮我查一下」这类与检索无关的客套或指令性措辞

三、绝对不可以：
    - 改动问题的意图、限定条件或时间范围
    - 编造原文里没有的事实、数字、公司名或日期
    - 回答这些问题（你只负责改写，不负责作答）
    - 输出解释、说明或多个候选

四、某一句已经没有可改的地方（例如日期两种写法都已出现、也没有可补的\
别名），就把那一句**原样返回**并把它的 changed 置为 false。宁可不动，\
也不要为了"改"而改。

五、**逐条对应，不得串号**（批量输入时最容易犯的错）
    - 输出 `items` 的条数必须与输入条数**完全一致**
    - 每条回它自己的编号，且保持输入顺序
    - 某一句改不动也要**照样回一条**（原样文本 + changed=false），
      **不许省略**：少回一条就会让后面所有条都错位

输出：**只输出一个 JSON 对象**，不要代码围栏、不要任何其它文字。
    {"items": [{"index": 1, "rewritten_query": "<改写后的查询语句>",
                "changed": <true 或 false>}, ...]}
"""


def render_user_message(queries: list[str]) -> str:
    """
    用户消息：这次要改的那几条（编号从 1 起）。

    只给原句，不给任何上游上下文 —— 改写只该依赖问句本身。给它看检索
    结果会让它"照着答案改"，那正是要避免的事。
    """

    lines = [
        f"请改写下面 {len(queries)} 句话，按系统提示里的规则输出 JSON"
        "（条数与编号必须一致）：",
        "",
    ]

    lines.extend(
        f"{index}. {query}" for index, query in enumerate(queries, start=1)
    )

    return "\n".join(lines)


def _render(**_: Any) -> str:
    """系统提示词无变量，可变部分全在用户消息里。"""

    return TEXT


PROMPT = PromptDefinition(
    key=ModelRole.QUERY_REWRITE,
    description=(
        "检索前的查询改写（批量）：日期两种写法都展开、补同义说法、"
        "去掉客套；不改意图、不编事实，逐条对应不串号。"
    ),
    render=_render,
)
