"""
处理器运行时需要的**进程级设施**。

    cache.py      工具结果缓存（带 TTL 与容量上限）
    events.py     工具生命周期事件 + 订阅总线（给 SSE 用）
    metrics.py    调用次数 / 耗时 / 成功率 / 错误率

为什么单独一层
--------------
这三个东西是"处理器要用、但处理器不该自己实现"的部分：缓存策略、
事件投递、指标口径都必须**只有一份**，否则两个观察者各记一套，
读出来对不上。与 document 模块把 tokenization 提成中立模块同理。

⚠️ 全是**进程内**的
------------------
项目没有 Redis / Prometheus / Celery（grep 零命中），因此：

    缓存    换进程就没了，多实例之间不共享
    事件    只有本进程内的订阅者收得到
    指标    进程重启清零

这不是没做完 —— 是当前的正确形态。要让它们跨进程，得先有那个
外部依赖（Redis / 消息队列 / Prometheus Pushgateway），
那时把这三个模块的实现换掉即可，处理器代码不用动。

⚠️ 本包在反射发现的根之下
------------------------
`walk_packages` 会把本包也 import 一遍（它是 `app.agent.tools.processor`
的子包）。这没问题 —— 三个模块都不定义 BaseToolProcessor 的子类，
注册表扫不到任何东西。
"""
