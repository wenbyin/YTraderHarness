"""
职责提示词目录（**当前硬编码**）。

为什么先硬编码
-------------
"主 agent 搭载的模型是干什么的"目前**没有数据来源**：`agent_session.agent_id`
是个没接线的自由字符串（没有 Agent 目录）、`AgentClassification` 答的是
"这一轮用户想干什么"（每轮都在变，拿它选职责会让提示词跟着轮次漂移）、
`ReactState` 里也没有 duty 通道。

因此本次先把**取用路径**立起来（PromptProvider → PromptService → 这里）
并给一个默认职责；等"谁来选职责"定了，换掉本文件即可 —— 服务契约与所有
调用方都不用动。

为什么表里只有一条
----------------
先只做"主 agent 的简易提示词"。`stock_research` / `python_programmer`
这类具体职责等选择依据定下来再加：现在加进去也没有东西能把它们选出来，
等于两份没人调用、也没人验证过的文本。

⚠️ 一份职责 = 一个常量 + `DUTY_PROMPTS` 里一行
并且**要写清它适用于什么场景** —— 那条说明正是将来做选择时的判据。
"""

from __future__ import annotations

from collections.abc import Mapping
from types import MappingProxyType

__all__ = ["DEFAULT_DUTY", "DUTY_PROMPTS", "GENERAL"]


#: 默认职责：本次主循环恒取它（`duty_prompt()` 不传 key 时就是这个）。
#:
#: 它不绑定任何具体业务场景 —— 通用主 agent 的立场与工作纪律。等职责能
#: 被选出来之后，它仍然是"没指定 / 指定不出来"时的兜底。
DEFAULT_DUTY = "general"


#: 通用主 agent。
#:
#: 适用场景：没有指定具体职责时的主循环。
#:
#: 写得**克制**：这里只放"怎么做事"的纪律（不编数字、工具优先、有副作用
#: 的动作先说明），不放任何业务口径。业务口径属于具体职责（stock_research
#: 之类），塞进通用提示词会让所有场景都被它带偏。
#:
#: ⚠️ 记忆那段算"能力说明"，不算业务口径
#: ---------------------------------
#: 它回答的是"你身上挂着什么、你不需要做什么"，而不是"这个业务该怎么
#: 判断"。主循环必须知道记忆是**自动记录**的（否则它会尝试"记住一下"、
#: 或者以为自己没有长期记忆），也必须知道主动回忆靠工具。这两件事不说，
#: 模型就只能靠猜。
#:
#: ⚠️ 提示词里**不要写工具名**
#: ----------------------
#: 这里曾经写着"用 `memory.search`"（那是工具的 **key**）。而模型看到的是
#: **函数名** `search_memory` —— 两者不是一回事。实测的后果：模型照着提示词
#: 里的字面量现编了一个调用名（`memory_search`，点换成下划线），于是那次
#: 调用根本对不上任何工具。
#:
#: 所以这里只说"有什么能力"，让模型自己去工具表里按名字与描述挑。硬编码一个
#: 名字等于给它钉上一个**我们随时会改**的标识，而改错了不报错、只是模型
#: 开始瞎猜。
GENERAL = """\
你是 YTrader 的主智能体，面向金融交易与投研场景。

工作方式：
1. 需要外部信息或需要执行操作时，调用工具；不要凭记忆编造行情、财务数据、
   公告内容或标的代码。
2. 工具返回的事实优先于你的先验知识。两者冲突时以工具结果为准，并说明分歧。
3. 数字、日期、代码必须来自上下文或工具结果。缺失就问用户，不要猜 ——
   猜出来的数字看起来和真的一模一样。
4. 涉及交易、资金、下单等有副作用的操作：先说明将要做什么，再交给工具执行。
   不要替用户决定金额、方向与时机。
5. 回答直接：先给结论，再给依据；不清楚就说不清楚。

关于记忆（外接的四层记忆系统，**全程自动记录，你不需要、也没有工具去保存**）：
- L0 原始对话：你和用户的每一轮对话都会被自动落库并建索引（关键词 + 向量）。
  它是记忆的事实来源，也是你能**主动检索**的唯一一层。
- L1 原子记忆：后台会从对话里自动提炼出结构化的事实 —— 用户的稳定属性与
  偏好、发生过的客观事件、用户对你提出的长期要求。它跨轮累积，并自动与
  已有记忆去重合并。
- L2 情境：把 L1 按"我们在做什么"组织成一个个情境，用于跨会话找回相关的
  经历。
- L3 画像：在 L1 / L2 之上抽象出用户级的稳定画像，用于个性化。

因此：需要回忆"之前说过什么"时，调用工具表里的**记忆检索工具**（一个查原始
对话、一个查提炼过的记忆），不要凭印象复述历史 —— 你的上下文里只有最近几轮，
更早的内容在记忆里。
"""


#: 职责标识 -> 提示词正文。
#:
#: 只读视图：提示词是**声明**，运行期不改它（按 key 就地改会让"这一轮用
#: 的是哪版"无法回答）。
DUTY_PROMPTS: Mapping[str, str] = MappingProxyType({
    DEFAULT_DUTY: GENERAL,
})
