"""
装配层：把一组组件装成可以启动的东西，并集中挂上业务实现。

为什么单独一层（而不是都写在 main.py 的 lifespan 里）
--------------------------------------------------
lifespan 是**唯一的组合根**，于是所有"先建谁、再建谁"的知识都堆在它
里面。单个组件各自只有几行，但一组相关组件合起来就是几十上百行，
读的人要在几百行之间来回跳才能回答一个具体问题
（"一条后台任务是怎么跑起来的"）。

更硬的一条理由在**注册点**上：有些装配必须 import 业务实现
（任务 Handler 的注册、图 handler 的注册），而 app/common 与 app/infra
都不允许 import 业务模块（依赖方向见 app/common/task/__init__.py）。
于是"既能 import 业务、又有权装配"的地方只能是组合根这一类模块 ——
本层就是它，lifespan 因此可以只留几行调度。

依赖方向（spec §13）：
    app/common  <-  app/services  <-  app/infra  <-  app/bootstrap  <-  main
本层可以 import 下面所有层，反过来一次都不行。
"""
